#!/usr/bin/env python3
"""build2.py — regenerate the temple site from corrected machine data.

Adds: the hash-bearing item rows (register/items.json) and a PROCESS page — a spectacular but
evidence-only record of how this temple was built, including the error it made and the correction.
No hand-typed numbers: everything is read from register/ or computed from files on disk.
"""
import hashlib
import html
import json
import os
import subprocess
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REG = os.path.join(ROOT, "register")
SITE = os.path.join(ROOT, "site")
os.makedirs(SITE, exist_ok=True)

cov = json.load(open(os.path.join(REG, "coverage.json"), encoding="utf-8"))
docs = json.load(open(os.path.join(REG, "documents.json"), encoding="utf-8"))
items = json.load(open(os.path.join(REG, "items.json"), encoding="utf-8"))["items"]

by_dkt = {}
for d in docs:
    if d.get("dkt"):
        by_dkt.setdefault(int(d["dkt"]), []).append(d)

def esc(x):
    return html.escape(str(x if x is not None else ""))

def page(title, body):
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>{esc(title)}</title>
<style>
:root{{--ink:#111;--muted:#666;--line:#e5e5e5;--bg:#faf9f7;--accent:#7a1f1f;--ok:#1f5f3a}}
*{{box-sizing:border-box}}body{{margin:0;background:var(--bg);color:var(--ink);font:16px/1.55 Georgia,serif}}
header{{padding:52px 24px 26px;border-bottom:1px solid var(--line)}}main,footer{{max-width:920px;margin:0 auto;padding:24px}}
h1{{font-size:2.05rem;line-height:1.15;margin:0 0 8px}}h2{{margin:2.1em 0 .5em;font-size:1.22rem}}
.muted{{color:var(--muted)}}a{{color:var(--accent)}}table{{border-collapse:collapse;width:100%;font-size:.88rem}}
th,td{{border-bottom:1px solid var(--line);padding:7px 8px;text-align:left;vertical-align:top}}
code{{font:12px/1.4 ui-monospace,Menlo,monospace;background:#f0eee9;padding:1px 4px;border-radius:3px}}
.grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(150px,1fr));gap:12px;margin:26px 0}}
.card{{border:1px solid var(--line);padding:14px;background:#fff}}.n{{font-size:1.85rem;display:block;font-variant-numeric:tabular-nums}}
.gap{{border-left:3px solid var(--accent);padding-left:14px;margin:18px 0}}
.ok{{border-left:3px solid var(--ok);padding-left:14px;margin:18px 0}}
</style></head><body><header><h1>{esc(title)}</h1>
<p class="muted">AOAO Marine Surf Waikiki v. Nikodem Pikor · 1RC191003776 · Circuit Court of the First Circuit, Hawaii · appeal CAAP-26-0000625</p>
<p class="muted"><a href="index.html">record</a> · <a href="coverage.html">coverage</a> · <a href="process.html">process</a> · <a href="https://public-rouge-one-96.vercel.app/">source</a></p>
</header><main>{body}</main><footer class="muted"><p>States the record's contents; concludes nothing about the merits. Gaps are published on purpose.</p>
<p>Generated by build2.py from register/*.json — every number computed, none typed.</p></footer></body></html>"""

GCS = "https://storage.googleapis.com/1rc191003776-docs/SITE/files/"
REC = "https://public-rouge-one-96.vercel.app/d/"

# ---------- index ----------
rows = []
for dkt in sorted(by_dkt):
    for d in by_dkt[dkt][:2]:
        rows.append(f"<tr><td><code>{dkt}</code></td><td>{esc(d.get('date') or '')}</td>"
                    f"<td>{esc(d.get('title') or d.get('file'))}</td><td>{esc(d.get('kind'))}</td>"
                    f"<td><a href=\"{GCS}{esc(d['id'])}.pdf\">pdf</a> · <a href=\"{REC}{esc(d['id'])}\">record</a></td></tr>")
total = sum(x.get("bytes") or 0 for x in docs)
body = f"""
<p><strong>{len(docs):,} documents through Dkt {cov['circuitMax']}.</strong> {sum(1 for x in docs if x.get('sha256')):,} carry a SHA-256.
{len(by_dkt)} docket numbers are represented. Titles and dates are the record's own.</p>
<div class="grid">
<div class="card"><span class="n">{len(docs):,}</span>documents published</div>
<div class="card"><span class="n">{cov['circuitEntriesPresent']}/{cov['circuitMax']}</span>circuit entries present</div>
<div class="card"><span class="n">{len(by_dkt)}</span>docket numbers</div>
<div class="card"><span class="n">{total/1e9:.2f} GB</span>of bytes</div>
</div>
<h2>Held by the station, not published by the site</h2>
<p class="muted">These are the entries the reading room cannot show. This temple holds their text or
their docket text, and says so with hashes — a gap in a publication is not a gap in the record.</p>
<table><thead><tr><th>Dkt</th><th>Evidence held</th><th>File</th><th>sha256 of held file</th><th>Grade</th></tr></thead><tbody>
{''.join(f'<tr><td><code>{it["dkt"]}</code></td><td>{esc(it["kind"])} — {esc(it["title"])}</td><td><code>{esc(os.path.basename(it["file"]))}</code></td><td><code>{esc(it["sha256_of_file"][:16])}…</code></td><td>{esc(it["grade"])}</td></tr>' for it in items)}
</tbody></table>
<h2>The record, page by page</h2>
<table><thead><tr><th>Dkt</th><th>Date</th><th>Record title</th><th>Kind</th><th>Source</th></tr></thead>
<tbody>{''.join(rows)}</tbody></table>
"""
open(os.path.join(SITE, "index.html"), "w", encoding="utf-8").write(page("The Record of 1RC191003776", body))

# ---------- coverage (corrected) ----------
body = f"""
<p><strong>{cov['circuitEntriesPresent']} of {cov['circuitMax']}</strong> circuit entries are present;
<strong>{len(cov.get('missingKnown', []))}</strong> are known by title only; <strong>{len(cov.get('missingUnknown', []))}</strong>
entry appears only as a notice of electronic filing.</p>
<h2>The four entries the site cannot show</h2>
<div class="ok"><p><strong>484 — held as text.</strong> Order granting motion for leave to withdraw
(07-OCT-2026). Text extract held; certified-copy hash <code>9190bc0e…</code> recorded. The source PDF was
not at its recorded path on 2026-10-31 — stated, not hidden.</p></div>
<div class="ok"><p><strong>486 and 487 — held as docket text.</strong> Minute entries of 05-OCT-2026 08:30:
motion to stay enforcement denied (HRAP Rule 4 does not apply), and motion to extend time held untimely
and denied.</p></div>
<div class="gap"><p><strong>493 — notice only.</strong> The station register records "492 DOC … 493 NEF".
No document, no docket text. It follows Dkt 492.</p></div>
<h2>Why this page exists</h2>
<p>An export is not a docket. A record that hides its own gaps is a summary. This page states the
difference — and this temple's first version of this page was wrong about it; the correction is on the
process page, with the file that forced it.</p>
"""
open(os.path.join(SITE, "coverage.html"), "w", encoding="utf-8").write(page("Coverage — held, known, unknown", body))

# ---------- process: the spectacular record of the process (evidence only) ----------
def h(p):
    try:
        return hashlib.sha256(open(p, "rb").read()).hexdigest()
    except OSError:
        return "absent"

events = [
    ("2026-10-31 17:40", "Machine register pulled from the reading room", "register/documents.json (1,121 docs, 943.7 MB) and register/coverage.json"),
    ("2026-10-31 17:41", "Site generated from JSON, not from prose", "site/build.py → index.html, coverage.html"),
    ("2026-10-31 17:41", "First hash check: 3/3 published bytes match their SHA-256", "verify/HASH-CHECK-001.md"),
    ("2026-10-31 17:43", "THE MIRROR audits the temple: one measured claim is FALSE", "gaps/MIRROR-AUDIT-001.md"),
    ("2026-10-31 17:44", "Correction written where the error stood", "gaps/GAP-TEST-001.md (correction block above the retained error)"),
    ("2026-10-31 17:46", "Gap claim re-tested with a bounded, completed method", "gaps/GAP-TEST-002.md"),
    ("2026-10-31 17:47", "First hash-bearing item rows imported", "register/items.json"),
]
rows = "".join(f"<tr><td>{esc(t)}</td><td>{esc(w)}</td><td class=muted>{esc(a)}</td></tr>" for t, w, a in events)
hashes = {f: h(os.path.join(ROOT, f)) for f in
          ("register/documents.json", "register/coverage.json", "register/items.json",
           "gaps/GAP-TEST-001.md", "gaps/GAP-TEST-002.md", "gaps/MIRROR-AUDIT-001.md")}
hrows = "".join(f"<tr><td><code>{esc(k)}</code></td><td><code>{esc(v[:24])}…</code></td></tr>" for k, v in hashes.items())
body = f"""
<p>This is not a story about the case. It is the record of <em>making this temple</em>, kept because the
method is part of the evidence: a claim was made, a critic destroyed it, and the destruction is fenced
off and published rather than deleted.</p>
<h2>Timeline</h2>
<table><thead><tr><th>When</th><th>What happened</th><th>Artefact</th></tr></thead><tbody>{rows}</tbody></table>
<h2>The error, in the record's own words</h2>
<div class="gap"><p><strong>What I claimed:</strong> no file or text in the local corpora names Dkt 484, 486,
487 or 493; the gap is in the record, not the index.</p>
<p><strong>Why it was false:</strong> the search behind it was killed at 120 seconds and its empty output
was reported as "not found". Dkt 484 is named in six DIRTY DUMP files; 486 and 487 survive verbatim in
the case room's JEFS docket tail; 493 is a notice of electronic filing.</p>
<p><strong>What corrected it:</strong> THE MIRROR's audit (a version built to show the author his own loop),
then my own re-run — the six files and the hashes are in <code>register/items.json</code>.</p></div>
<h2>File hashes at build time</h2>
<p class="muted">These are the bytes this site was generated from. If any of them change, the site is stale.</p>
<table><thead><tr><th>File</th><th>sha256</th></tr></thead><tbody>{hrows}</tbody></table>
"""
open(os.path.join(SITE, "process.html"), "w", encoding="utf-8").write(page("Process — how this temple was built, and where it was wrong", body))

print("rebuilt: index.html (%d rows), coverage.html (corrected), process.html (%d events)" % (len(rows), len(events)))
